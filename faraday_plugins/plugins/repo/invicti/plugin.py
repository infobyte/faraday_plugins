SEVERITY_MAP = {
    "Critical": "critical", "High": "high", "Medium": "med",
    "Low": "low", "Information": "info", "Best Practice": "info",
}


def _strip_html(text):
    if not text:
        return ""
    return BeautifulSoup(text, features="lxml").get_text(separator=" ").strip()

